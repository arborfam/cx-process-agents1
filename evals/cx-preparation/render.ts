import { CHECKS, type Check } from './criteria.ts';

const KIND: Record<Check['kind'], string> = {
  expected: 'Очікуваний факт',
  forbidden: 'Заборонений домисел',
  allowed_unknown: 'Допустима невизначеність',
  human: 'Оцінює людина',
};

const STAGES: [number, string][] = [
  [1, 'Етап 1: Jira-запит і розмова із замовником (+ навчальна межа від аналітика SRC-00)'],
  [2, 'Етап 2: розмова з відповідальною за підготовку агентів у CX (SRC-03)'],
  [3, 'Етап 3: розмова з Growth (SRC-04)'],
  [4, 'Етап 4: програми знижок/комісій, команда релізу, довідка (SRC-05, SRC-06, SRC-07)'],
  [5, 'Етап 5: синтетичне уточнення (вигадано для тесту): SRC-08p у позитивному сценарії, SRC-08n у негативному; для негативного — явне уточнення SRC-09'],
];

const row = (c: Check) => `| ${c.id} | ${KIND[c.kind]} | ${c.title.replace(/\|/g, '/')} | ${c.run ? 'програма (сигнал)' : 'людина'} |`;

export function renderCriteriaMd(): string {
  const out: string[] = [];
  out.push(`# Критерії оцінки агента 1: навчальний сценарій «Підготовка CX до продуктових змін»

> Файл згенеровано з \`evals/cx-preparation/criteria.ts\` (\`node --import tsx scripts/build-criteria-md.ts\`). Не редагуйте вручну: тест порівнює файл із кодом.
> **Ці критерії не входять у контекст агента** і не підключені до застосунку (\`src/\` їх не читає; це перевіряє тест).

## Як користуватись

- Критерії **не вимагають дослівного збігу**: агент може формулювати по-своєму. Програмні перевірки шукають змістові ознаки (регулярні вирази) і є **сигналами**: «не пройдено» — привід подивитися, «пройдено» — не доказ якості. Остаточну оцінку виставляє людина (рядки «Оцінює людина»).
- Види записів: **очікуваний факт** — має бути відображено; **заборонений домисел** — не повинен з’явитися; **допустима невизначеність** — агент може (і має) лишити це відкритим, не вигадуючи; **оцінює людина** — програма не може перевірити.
- Загальні перевірки (G*) застосовуються до кожного етапу. Спосіб перевірки: програмні — \`evaluate()\` у criteria.ts; людські — за списком у цьому файлі після кожного запуску.
- Оцінка двох сценаріїв робиться окремо; результати одного не переносяться на інший.
- Сценарій А (позитивний) завершується синтетичним уточненням SRC-08p; сценарій Б (негативний) отримує SRC-08n без відповіді про перенесення/вилучення запуску.
- Усі джерела синтетичні; уточнення SRC-08p/08n/09 вигадані для тесту й не переписують оригінальних матеріалів.

## Загальні перевірки (усі етапи)
`);
  out.push('| ID | Тип | Що перевіряємо | Спосіб |\n|---|---|---|---|');
  out.push(...CHECKS.filter((c) => c.stage === 'all').map(row));
  for (const [n, title] of STAGES) {
    out.push(`\n## ${title}\n`);
    out.push('| ID | Тип | Що перевіряємо | Спосіб |\n|---|---|---|---|');
    out.push(...CHECKS.filter((c) => c.stage === n).map((c) => row(c) + (c.variant ? ` Сценарій: ${c.variant === 'positive' ? 'А (позитивний)' : 'Б (негативний)'}.` : '')).map((l) => l));
  }
  out.push(`
## Що вважається успіхом сценаріїв

- **Сценарій А:** після етапу 5 і перевірки людиною версію можна прийняти й погодити: критичних прогалин немає (початок, завершення, гілки визначені), а програмні перевірки (потік, блокери) не показують критичного.
- **Сценарій Б:** після етапу 5 агент **не вигадує** відповіді; опис лишається чернеткою; погодження й дозвіл на BPMN заблоковано програмою. Після **явного уточнення** (SRC-09) з’являється нова версія, яка потребує перевірки й погодження.
- **Приховане уточнення SRC-09** не повинно бути ні в джерелах, ні в версіях, ні в резюме негативного кейсу до явної дії аналітика (перевіряє тест за відбитками з \`hidden-fingerprints.json\`).
`);
  return out.join('\n') + '\n';
}
